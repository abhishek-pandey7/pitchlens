// Generates lib/types.ts from the JSON Schemas exported by the engine
// (python -m pitchlens.schema.export_jsonschema). The engine's Pydantic models are the source of truth.
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const schemaDir = path.join(root, "lib", "schemas");
const outFile = path.join(root, "lib", "types.ts");

// Pydantic titles every property, which makes the compiler emit one alias per field (and invites name
// clashes across schemas). Strip property-level titles so only models and enums become named types.
const stripPropertyTitles = (node) => {
  if (Array.isArray(node)) return node.forEach(stripPropertyTitles);
  if (!node || typeof node !== "object") return;
  if (node.properties) for (const prop of Object.values(node.properties)) delete prop.title;
  for (const value of Object.values(node)) stripPropertyTitles(value);
};

const toPascal = (name) => name.replace(/(^|_)(\w)/g, (_, __, c) => c.toUpperCase());

const files = (await readdir(schemaDir)).filter((f) => f.endsWith(".schema.json")).sort();
const seen = new Set();
const chunks = [
  "// AUTO-GENERATED by scripts/gen-types.mjs. Do not edit; change the engine schemas instead.\n",
];

for (const file of files) {
  const schema = JSON.parse(await readFile(path.join(schemaDir, file), "utf8"));
  stripPropertyTitles(schema);
  const name = toPascal(file.replace(".schema.json", ""));
  let ts = await compile(schema, name, { bannerComment: "", additionalProperties: false, strictIndexSignatures: false });
  // Shared $defs (enums, nested models) appear in several schemas; keep the first declaration only.
  ts = ts
    .split(/\n(?=export )/)
    .filter((decl) => {
      const m = decl.match(/^export (?:type|interface) (\w+)/);
      if (!m) return true;
      if (seen.has(m[1])) return false;
      seen.add(m[1]);
      return true;
    })
    .join("\n");
  chunks.push(ts);
}

await writeFile(outFile, chunks.join("\n"));
console.log(`wrote ${path.relative(root, outFile)} from ${files.length} schemas`);
